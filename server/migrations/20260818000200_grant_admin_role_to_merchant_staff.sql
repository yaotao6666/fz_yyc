-- ============================================================
-- 为 merchant 账号授予全部菜单与功能权限
-- 约束：纯 SQL 单条执行，禁止存储过程 / BEGIN...END / WHILE / IF...THEN
--       幂等：依赖唯一索引 uk_sys_role_menus / uk_merchant_staff_roles + INSERT IGNORE，可重复执行
-- ============================================================

-- ============================================================
-- 1. 确保「超级管理员」角色（sys_roles.id=1）存在且启用
-- ============================================================
INSERT IGNORE INTO sys_roles (id, name, code, remark, status)
VALUES (1, '超级管理员', 'admin', '拥有全部菜单权限(系统预置)', 1);

-- ============================================================
-- 2. 确保「超级管理员」绑定全部现有菜单（含后续新增菜单）
-- ============================================================
INSERT IGNORE INTO sys_role_menus (role_id, menu_id)
SELECT 1, id FROM sys_menus;

-- ============================================================
-- 3. 将全部现有 merchant_staffs 账号绑定到「超级管理员」角色
--    使所有 merchant 账号（含 role='staff'）获得全部菜单与功能权限
-- ============================================================
INSERT IGNORE INTO merchant_staff_roles (staff_id, role_id)
SELECT id, 1 FROM merchant_staffs;
